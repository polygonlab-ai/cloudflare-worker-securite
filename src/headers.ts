/**
 * Header computation. Pure functions: the result depends only on the policy of the host and on
 * the headers sent by the origin, so every case is tested without network.
 */

import type { HostPolicy } from "./types";

export const CSP = "Content-Security-Policy";
export const CSP_REPORT_ONLY = "Content-Security-Policy-Report-Only";

/** What to do with the headers of a response. Removals are applied first. */
export interface HeaderChanges {
    readonly remove: readonly string[];
    readonly set: readonly (readonly [name: string, value: string])[];
}

/** CSP of the configuration, with the `frame-ancestors` directive; `null` when there is none. */
export function configuredCsp(policy: HostPolicy): string | null {
    if (policy.csp === false) {
        return null;
    }
    const directives = policy.csp
        .split(";")
        .map((directive) => directive.trim())
        .filter((directive) => directive !== "");
    if (policy.frameAncestors !== false) {
        directives.push(`frame-ancestors '${policy.frameAncestors}'`);
    }
    return directives.join("; ");
}

/** Security headers other than the CSP, in a stable order. */
function baseHeaders(policy: HostPolicy): [string, string][] {
    const headers: [string, string][] = [];
    if (policy.hsts !== false) {
        headers.push(["Strict-Transport-Security", policy.hsts]);
    }
    if (policy.contentTypeOptions !== false) {
        headers.push(["X-Content-Type-Options", policy.contentTypeOptions]);
    }
    if (policy.referrerPolicy !== false) {
        headers.push(["Referrer-Policy", policy.referrerPolicy]);
    }
    if (policy.permissionsPolicy !== false) {
        headers.push(["Permissions-Policy", policy.permissionsPolicy]);
    }
    if (policy.crossOriginOpenerPolicy !== false) {
        headers.push(["Cross-Origin-Opener-Policy", policy.crossOriginOpenerPolicy]);
    }
    if (policy.crossOriginResourcePolicy !== false) {
        headers.push(["Cross-Origin-Resource-Policy", policy.crossOriginResourcePolicy]);
    }
    if (policy.frameAncestors !== false) {
        headers.push(["X-Frame-Options", policy.frameAncestors === "none" ? "DENY" : "SAMEORIGIN"]);
    }
    return headers;
}

/**
 * Changes to apply to a response of the origin.
 *
 * CSP modes:
 * - `override`: the CSP of the configuration replaces the one of the origin;
 * - `keep-origin`: the CSP of the origin is kept untouched; the CSP of the configuration is
 *   applied only when the origin sends none;
 * - `report-only`: the CSP of the configuration is sent as `Content-Security-Policy-Report-Only`
 *   (the browser reports violations without blocking); the CSP of the origin is kept.
 */
export function planHeaders(policy: HostPolicy, origin: Headers): HeaderChanges {
    const set = baseHeaders(policy);
    const csp = configuredCsp(policy);
    if (csp !== null) {
        if (policy.cspMode === "report-only") {
            set.push([CSP_REPORT_ONLY, csp]);
        } else if (policy.cspMode === "override" || !origin.has(CSP)) {
            set.push([CSP, csp]);
        }
    }
    return { remove: policy.removeHeaders, set };
}

/** Applies the changes to a mutable `Headers` object. */
export function applyChanges(headers: Headers, changes: HeaderChanges): void {
    for (const name of changes.remove) {
        headers.delete(name);
    }
    for (const [name, value] of changes.set) {
        headers.set(name, value);
    }
}

/**
 * Headers of a response generated by the Worker (maintenance page, 403). The CSP is always the
 * strict policy given here: there is no origin CSP to keep.
 */
export function generatedHeaders(policy: HostPolicy, contentType: string, csp: string): Headers {
    const headers = new Headers({ "Content-Type": contentType, "Cache-Control": "no-store" });
    applyChanges(headers, { remove: [], set: [...baseHeaders(policy), [CSP, csp]] });
    return headers;
}
